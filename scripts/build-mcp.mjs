import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const result=await build({absWorkingDir:root,entryPoints:['apps/mcp/server.ts'],outfile:'apps/mcp/glassport.mjs',bundle:true,platform:'node',format:'esm',target:'node24',metafile:true,legalComments:'inline'});
const packages=new Set();
for(const input of Object.keys(result.metafile.inputs)){
  const match=input.match(/^node_modules\/(?:@[^/]+\/)?[^/]+/);
  if(match)packages.add(match[0]);
}
let notices='# Bundled MCP dependency licenses\n\nGenerated by `npm run build:mcp`. Original Glassport code remains MIT.\n';
for(const folder of [...packages].sort()){
  const manifest=JSON.parse(await readFile(join(root,folder,'package.json'),'utf8'));
  let license;
  for(const name of ['LICENSE','LICENSE.md','LICENSE.txt','license','license.md','LICENCE']){
    try{license=await readFile(join(root,folder,name),'utf8');break;}catch{}
  }
  if(!license)throw new Error(`The bundled dependency ${manifest.name} has no retained license.`);
  notices+=`\n## ${manifest.name} ${manifest.version}\n\n${license}\n`;
}
await mkdir(join(root,'LICENSES'),{recursive:true});
await writeFile(join(root,'LICENSES/MCP-DEPENDENCIES.md'),notices);
console.log(JSON.stringify({bundle:'apps/mcp/glassport.mjs',dependencies:packages.size}));
